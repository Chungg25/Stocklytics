"""Runs one Hermes Agent container per user, wired to their personal Telegram bot and our MCP server.

Each container gets its own HERMES_HOME (/opt/data) with:
- .env         TELEGRAM_BOT_TOKEN, TELEGRAM_ALLOWED_USERS (only the owner), STOCKLYTICS_API_KEY
- config.yaml  MCP server, disabled risky toolsets, our trading skill directory
ChatGPT sign-in uses Hermes' own device-code flow (`hermes auth add openai-codex`), whose
URL and code we relay to the user in Telegram.
"""
from __future__ import annotations

import logging
import os
import re
import threading
from dataclasses import dataclass
from pathlib import Path
from typing import Callable, Protocol

import docker
from docker.errors import NotFound

from stockbot.config import settings

log = logging.getLogger(__name__)

ANSI_RE = re.compile(r"\x1b\[[0-9;]*m")
URL_RE = re.compile(r"(https://\S+/codex/device\S*)")
CODE_RE = re.compile(r"Enter this code:\s*\n?\s*([A-Z0-9][A-Z0-9-]{4,})", re.I)

CONFIG_TEMPLATE = """# Generated by Stocklytics — do not edit by hand.
mcp_servers:
  stocklytics:
    url: "{mcp_url}"
    headers:
      Authorization: "Bearer ${{STOCKLYTICS_API_KEY}}"
    timeout: 180
    trust: full

skills:
  external_dirs:
    - /opt/stocklytics/skills

platforms:
  telegram:
    extra:
      # Keep the "/" menu short for non-technical users.
      command_menu:
        max_commands: 4
        priority_mode: replace
        priority:
          - new
          - stocklytics_trading

agent:
  # Trading-alert assistant only: no shell, files, browser, code execution or sub-agents.
  disabled_toolsets:
    - terminal
    - file
    - browser
    - computer_use
    - code_execution
    - delegation
    - kanban
    - image_gen
    - video_gen
"""


@dataclass
class LoginPrompt:
    url: str
    code: str


class Provisioner(Protocol):
    def provision(self, telegram_user_id: int, bot_token: str, api_key: str) -> str: ...
    def update_token(self, telegram_user_id: int, bot_token: str, api_key: str) -> None: ...
    def start_chatgpt_login(self, telegram_user_id: int, on_prompt: Callable[[LoginPrompt], None],
                            on_done: Callable[[bool, str], None]) -> None: ...
    def restart(self, telegram_user_id: int) -> None: ...
    def stop(self, telegram_user_id: int) -> None: ...


def container_name(telegram_user_id: int) -> str:
    return f"stockbot-hermes-{telegram_user_id}"


class DockerProvisioner:
    def __init__(self, client: docker.DockerClient | None = None):
        self.client = client or docker.from_env()

    def _data_dir(self, telegram_user_id: int) -> Path:
        return Path(settings.hermes_data_root) / str(telegram_user_id)

    def _write_files(self, telegram_user_id: int, bot_token: str, api_key: str, with_config: bool = True) -> Path:
        d = self._data_dir(telegram_user_id)
        d.mkdir(parents=True, exist_ok=True)
        env = d / ".env"
        env.write_text(
            f"TELEGRAM_BOT_TOKEN={bot_token}\n"
            f"TELEGRAM_ALLOWED_USERS={telegram_user_id}\n"
            f"STOCKLYTICS_API_KEY={api_key}\n"
        )
        os.chmod(env, 0o600)
        if with_config:
            (d / "config.yaml").write_text(CONFIG_TEMPLATE.format(mcp_url=settings.mcp_url_for_hermes))
        return d

    def provision(self, telegram_user_id: int, bot_token: str, api_key: str) -> str:
        """Create (or recreate) the user's Hermes container. Returns the container name."""
        name = container_name(telegram_user_id)
        data_dir = self._write_files(telegram_user_id, bot_token, api_key)
        try:
            old = self.client.containers.get(name)
            old.remove(force=True)
        except NotFound:
            pass
        kwargs = dict(
            name=name, command=["gateway", "run"], detach=True,
            volumes={str(data_dir): {"bind": "/opt/data", "mode": "rw"}},
            restart_policy={"Name": "unless-stopped"}, mem_limit=settings.hermes_mem_limit,
            nano_cpus=500_000_000, labels={"app": "stockbot-hermes", "telegram_user_id": str(telegram_user_id)},
        )
        if settings.hermes_network:
            kwargs["network"] = settings.hermes_network
        self.client.containers.run(settings.hermes_image, **kwargs)
        log.info("provisioned %s", name)
        return name

    def update_token(self, telegram_user_id: int, bot_token: str, api_key: str) -> None:
        # Keep config.yaml: Hermes stored the ChatGPT provider selection in it at login.
        self._write_files(telegram_user_id, bot_token, api_key, with_config=False)
        self.restart(telegram_user_id)

    def start_chatgpt_login(self, telegram_user_id: int, on_prompt: Callable[[LoginPrompt], None],
                            on_done: Callable[[bool, str], None]) -> None:
        """Run Hermes' ChatGPT device-code login in the container (background thread)."""
        container = self.client.containers.get(container_name(telegram_user_id))

        def worker() -> None:
            buf, prompted = "", False
            try:
                exec_id = self.client.api.exec_create(container.id, ["hermes", "auth", "add", "openai-codex"],
                                                      stdout=True, stderr=True, stdin=False, tty=False)["Id"]
                for chunk in self.client.api.exec_start(exec_id, stream=True):
                    buf += ANSI_RE.sub("", chunk.decode(errors="replace"))
                    if not prompted:
                        url, code = URL_RE.search(buf), CODE_RE.search(buf)
                        if url and code:
                            prompted = True
                            on_prompt(LoginPrompt(url=url.group(1), code=code.group(1)))
                exit_code = self.client.api.exec_inspect(exec_id).get("ExitCode")
                ok = exit_code == 0 and prompted
                if ok:
                    self.restart(telegram_user_id)  # gateway picks up the new provider
                on_done(ok, "" if ok else buf[-500:])
            except Exception as e:  # report every failure to the user instead of dying silently
                log.exception("ChatGPT login failed for %s", telegram_user_id)
                on_done(False, str(e))

        threading.Thread(target=worker, name=f"login-{telegram_user_id}", daemon=True).start()

    def restart(self, telegram_user_id: int) -> None:
        self.client.containers.get(container_name(telegram_user_id)).restart(timeout=20)

    def stop(self, telegram_user_id: int) -> None:
        try:
            self.client.containers.get(container_name(telegram_user_id)).remove(force=True)
        except NotFound:
            pass
